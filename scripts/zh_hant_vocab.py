import re

# 대륙에서 '안'을 뜻하는 里 는 대만에서 裡 로 적는다. 다만 거리 단위(公里·英里)는 里 그대로다.
_LI = re.compile(r"(?<![公英])里")


def to_taiwan(text: str) -> str:
    # 1) 고유명사를 자리표시자로 빼 둔다 - 뒤의 일반 규칙이 그 안을 건드리지 못하게.
    held = []
    for a, b in PROPER_NOUNS:
        if a in text:
            text = text.replace(a, f"\x00{len(held)}\x00")
            held.append(b)
    # 2) 일반 어휘
    for a, b in RULES:
        text = text.replace(a, b)
    text = _LI.sub("裡", text)
    # 대만은 인용에 「」를 쓴다. 짝이 맞을 때만 바꾼다.
    if text.count('“') == text.count('”'):
        text = text.replace('“', '「').replace('”', '」')
    # 3) 빼 뒀던 고유명사를 제자리에 돌려놓는다.
    for i, b in enumerate(held):
        text = text.replace(f"\x00{i}\x00", b)
    return text
